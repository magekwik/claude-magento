#!/usr/bin/env bash
set -u
[ -f CLAUDE.md ] || { echo "CLAUDE.md missing"; exit 1; }
[ "$(grep -c '<!-- magento:begin -->' CLAUDE.md)" = "1" ] || { echo "begin marker count != 1"; exit 1; }
[ "$(grep -c '<!-- magento:end -->' CLAUDE.md)" = "1" ] || { echo "end marker count != 1"; exit 1; }
grep -q '2\.4\.9' CLAUDE.md || { echo "version missing"; exit 1; }
grep -q 'Acme_Catalog' CLAUDE.md || { echo "module missing"; exit 1; }
grep -q 'Luma' CLAUDE.md || { echo "frontend stack missing"; exit 1; }
grep -q 'developer' CLAUDE.md || { echo "mode missing"; exit 1; }
grep -q '`bin/magento' CLAUDE.md || { echo "native prefix missing"; exit 1; }
if grep -Eq 'warden|ddev|docker compose' CLAUDE.md; then echo "wrong env prefix"; exit 1; fi
R=.claude/rules/magento.md
[ -f "$R" ] || { echo "rules file missing"; exit 1; }
head -1 "$R" | grep -q '^<!-- generated by the magento plugin v' || { echo "rules header missing"; exit 1; }
grep -q '^## Frontend — Luma' "$R" || { echo "Luma section missing"; exit 1; }
if grep -q '^## Frontend — Hyvä' "$R"; then echo "Hyvä section present on Luma project"; exit 1; fi
exit 0
